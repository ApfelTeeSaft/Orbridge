const GcnOpcode* FindGcnOpcode(GcnOpcodeFamily family, std::uint32_t opcode) {
    switch (family) {
        case GcnOpcodeFamily::Sop2: return find(sop2Opcodes, opcode);
        case GcnOpcodeFamily::Sopk: return find(sopkOpcodes, opcode);
        case GcnOpcodeFamily::Sop1: return find(sop1Opcodes, opcode);
        case GcnOpcodeFamily::Sopc: return find(sopcOpcodes, opcode);
        case GcnOpcodeFamily::Sopp: return find(soppOpcodes, opcode);
        case GcnOpcodeFamily::Vop1: return find(vop1Opcodes, opcode);
        case GcnOpcodeFamily::Vop2: return find(vop2Opcodes, opcode);
        case GcnOpcodeFamily::Vopc: return find(vopcOpcodes, opcode);
        case GcnOpcodeFamily::Vintrp: return find(vintrpOpcodes, opcode);
        case GcnOpcodeFamily::Smrd: return find(smrdOpcodes, opcode);
    }
    return nullptr;
}

