template<typename TEntry, std::size_t TCount>
const TEntry* find(const std::array<TEntry, TCount>& entries, std::uint32_t opcode) {
    const auto found = std::lower_bound(entries.begin(), entries.end(), opcode, [](const TEntry& entry, std::uint32_t value) { return entry.opcode < value; });
    return found != entries.end() && found->opcode == opcode ? &*found : nullptr;
}

